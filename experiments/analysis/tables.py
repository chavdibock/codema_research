"""All tables of spec §10 in LaTeX (booktabs, ACM sigconf width) and Markdown.

    python -m experiments.analysis.tables --summary summary --out paper/tables

Styling (spec §5.1): bold = safe (normalized cost <= 1), gray = unsafe, blue = best safe
model per task. Missing runs are shown as "–"; nothing is filled in by hand. The optional
row "CDT (reported in [CDT])" is read from analysis/reported_cdt.csv (task,R_norm,C_norm)
if that file exists; it is not shipped with the code.
"""

import argparse
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Dict, List, Optional, Sequence, Tuple

import numpy as np
import pandas as pd

from experiments.analysis.aggregate import load
from experiments.analysis.stats import (BASELINES, DISPLAY, OUR_MODELS, TASK_ORDER, TASK_SHORT,
                                        cell_style, rank_key, seed_summary)

MISSING = "–"


@dataclass
class Cell:
    text: str
    style: str = "plain"  # plain | safe | unsafe | best | missing | header | label


@dataclass
class Table:
    name: str
    caption: str
    header: List[List[Cell]]
    rows: List[List[Cell]] = field(default_factory=list)
    col_align: str = ""
    notes: str = ""


# ------------------------------------------------------------------ renderers
def _latex_cell(c: Cell) -> str:
    t = c.text.replace("_", r"\_").replace("%", r"\%").replace("±", r"$\pm$")
    if c.style == "safe":
        return rf"\textbf{{{t}}}"
    if c.style == "best":
        return rf"\textcolor{{blue}}{{\textbf{{{t}}}}}"
    if c.style == "unsafe":
        return rf"\textcolor{{gray}}{{{t}}}"
    return t


def to_latex(t: Table) -> str:
    ncol = len(t.rows[0]) if t.rows else len(t.header[-1])
    align = t.col_align or ("l" + "c" * (ncol - 1))
    lines = [r"% generated by experiments/analysis/tables.py - do not edit by hand",
             r"\begin{table*}[t]", r"\centering", r"\small",
             rf"\caption{{{t.caption}}}", rf"\label{{tab:{t.name}}}",
             r"\resizebox{\textwidth}{!}{%", rf"\begin{{tabular}}{{{align}}}", r"\toprule"]
    for h in t.header:
        lines.append(" & ".join(_latex_cell(c) for c in h) + r" \\")
    lines.append(r"\midrule")
    for r in t.rows:
        if r and r[0].style == "rule":
            lines.append(r"\midrule")
            continue
        lines.append(" & ".join(_latex_cell(c) for c in r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}"]
    if t.notes:
        lines.append(rf"\\[2pt]\footnotesize {t.notes}")
    lines.append(r"\end{table*}")
    return "\n".join(lines) + "\n"


def _md_cell(c: Cell) -> str:
    t = c.text.replace("|", "/")
    if c.style == "safe":
        return f"**{t}**"
    if c.style == "best":
        return f"***{t}***"
    if c.style == "unsafe":
        return f"<span style='color:gray'>{t}</span>"
    return t


def to_markdown(t: Table) -> str:
    out = [f"### {t.caption}", ""]
    hdr = t.header[-1]
    if len(t.header) > 1:  # flatten multi-row headers
        top = []
        for c in t.header[0]:
            top.extend([c.text] * int(c.style.split(":")[1]) if c.style.startswith("span:")
                       else [c.text])
        hdr = [Cell(f"{a} {b.text}".strip()) for a, b in zip(top, t.header[-1])]
    out.append("| " + " | ".join(c.text for c in hdr) + " |")
    out.append("|" + "---|" * len(hdr))
    for r in t.rows:
        if r and r[0].style == "rule":
            continue
        out.append("| " + " | ".join(_md_cell(c) for c in r) + " |")
    out.append("")
    out.append("Bold: safe (normalized cost <= 1); bold italic: best safe; gray: unsafe; "
               f"{MISSING}: run missing." + (f" {t.notes}" if t.notes else ""))
    return "\n".join(out) + "\n"


def write(t: Table, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{t.name}.tex").write_text(to_latex(t))
    (out / f"{t.name}.md").write_text(to_markdown(t))


# ------------------------------------------------------------------ helpers
def fmt(mean: float, std: Optional[float] = None, digits: int = 2) -> str:
    if mean is None or np.isnan(mean):
        return MISSING
    if std is None or np.isnan(std):
        return f"{mean:.{digits}f}"
    return f"{mean:.{digits}f} ± {std:.{digits}f}"


def span_header(groups: Sequence[str], sub: Sequence[str], first: str = "Method"):
    top = [Cell("")] + [Cell(g, f"span:{len(sub)}") for g in groups]
    bottom = [Cell(first)] + [Cell(s) for _ in groups for s in sub]
    return [top, bottom]


def _latex_span_fix(t: Table) -> Table:
    """Turn 'span:n' header cells into \\multicolumn for LaTeX."""
    for c in t.header[0]:
        if c.style.startswith("span:"):
            n = int(c.style.split(":")[1])
            c.text = rf"\multicolumn{{{n}}}{{c}}{{{c.text}}}"
            c.style = "header"
    return t


def reward_cost_table(name: str, caption: str, runs: pd.DataFrame,
                      row_specs: List[Tuple[str, Callable[[pd.DataFrame], pd.DataFrame]]],
                      tasks: Sequence[str] = TASK_ORDER, extra_rows: Optional[List] = None,
                      with_avg: bool = True, std: bool = True) -> Table:
    """Rows = methods; columns = task x (reward up, cost down) [+ average]."""
    groups = [TASK_SHORT.get(t, t) for t in tasks] + (["Average"] if with_avg else [])
    t = Table(name, caption, span_header(groups, ["R↑", "C↓"]))
    stats: Dict[str, Dict[str, Tuple[float, float, float, float]]] = {}
    for label, sel in row_specs:
        df = sel(runs) if not runs.empty else runs
        s = seed_summary(df, ["task"]) if not df.empty else pd.DataFrame()
        per = {}
        for task in tasks:
            row = s[s["task"] == task] if not s.empty else s
            if len(row):
                r = row.iloc[0]
                per[task] = (r["R_norm_mean"], r["R_norm_std"], r["C_norm_mean"],
                             r["C_norm_std"])
            else:
                per[task] = (np.nan, np.nan, np.nan, np.nan)
        if with_avg:
            vals = np.array([per[x] for x in tasks])
            complete = not np.isnan(vals[:, 0]).any()
            per["Average"] = ((vals[:, 0].mean(), np.nan, vals[:, 2].mean(), np.nan)
                              if complete else (np.nan,) * 4)
        stats[label] = per
    cols = list(tasks) + (["Average"] if with_avg else [])
    best = {}
    for c in cols:
        cands = [(rank_key(v[c][0], v[c][2]), lab) for lab, v in stats.items()]
        cands = [x for x in cands if x[0][0] == 0]
        best[c] = min(cands)[1] if cands else None
    for label, per in stats.items():
        row = [Cell(label, "label")]
        for c in cols:
            rm, rs, cm, cs = per[c]
            st = cell_style(cm, best[c] == label)
            row.append(Cell(fmt(rm, rs if std else None), st))
            row.append(Cell(fmt(cm, cs if std else None), st))
        t.rows.append(row)
    for extra in extra_rows or []:
        t.rows.append(extra)
    t.col_align = "l" + "cc" * len(cols)
    return t


def sel(**kw) -> Callable[[pd.DataFrame], pd.DataFrame]:
    """Row selector on runs (exp, model, variant, target_C, seeds)."""

    def f(df: pd.DataFrame) -> pd.DataFrame:
        m = np.ones(len(df), dtype=bool)
        for k, v in kw.items():
            if k == "seeds":
                m &= df["seed"].isin(v).to_numpy()
            elif isinstance(v, (list, tuple, set)):
                m &= df[k].isin(v).to_numpy()
            else:
                m &= (df[k].fillna("") == v).to_numpy()
        return df[m]

    return f


def reported_row(tasks: Sequence[str]) -> Optional[List[Cell]]:
    path = Path(__file__).with_name("reported_cdt.csv")
    row = [Cell("CDT (reported in [CDT])", "label")]
    rep = pd.read_csv(path) if path.exists() else pd.DataFrame(columns=["task"])
    vals = []
    for task in tasks:
        r = rep[rep["task"] == task]
        if len(r):
            vals.append((float(r["R_norm"].iloc[0]), float(r["C_norm"].iloc[0])))
        else:
            vals.append((np.nan, np.nan))
    for rm, cm in vals:
        row += [Cell(fmt(rm), "unsafe" if np.isnan(rm) else "plain"),
                Cell(fmt(cm), "unsafe" if np.isnan(cm) else "plain")]
    arr = np.array(vals)
    complete = not np.isnan(arr).any()
    row += [Cell(fmt(arr[:, 0].mean() if complete else np.nan)),
            Cell(fmt(arr[:, 1].mean() if complete else np.nan))]
    for c in row[1:]:
        c.style = "unsafe"  # gray row, kept apart from our reproduction (D4)
    return row


