def _eff_value(eff: pd.DataFrame, model: str, metric: str, stat: str, **kw) -> Tuple[float, float]:
    d = eff[(eff["model"] == model) & (eff["metric"] == metric) & (eff["stat"] == stat)]
    for k, v in kw.items():
        d = d[d[k] == v]
    if not len(d):
        return (np.nan, np.nan)
    per_rep = d.groupby("repetition")["value"].mean()  # average over tasks within a rep
    return float(per_rep.mean()), float(per_rep.std()) if len(per_rep) > 1 else np.nan


def table2(eff: pd.DataFrame, train_precision: str = "bf16") -> Table:
    cols = ["Params", "Size (MB)", "Train s/step", "Train h (100k)", "Train mem (MB)",
            "Infer GPU ms", "Infer CPU-1 ms", "Infer mem GPU (MB)", "Infer mem CPU (MB)",
            "Recurrent ms", "State (KB)"]
    t = Table("table2_efficiency", f"Efficiency at $K=10$ (mean ± std over 3 repetitions; "
              f"training in {train_precision}, sampler included, batch 2048; inference batch 1, "
              "fp32, median (p95)).", [[Cell("Model")] + [Cell(c) for c in cols]])
    if eff.empty:
        eff = pd.DataFrame(columns=["model", "metric", "stat", "value", "device", "mode", "K",
                                    "batch", "precision", "repetition", "weights", "threads"])
    e = eff[(eff["K"].astype(str) == "10")]
    e = e[~e["weights"].astype(str).str.startswith("fresh_scaling")]
    raw: Dict[str, List[float]] = {}
    for m in OUR_MODELS:
        g = lambda metric, stat, **kw: _eff_value(e, m, metric, stat, **kw)  # noqa: E731
        p = g("params_total", "value")
        size = g("static_model_mem", "value")
        sps = g("train_step_s", "median", device="cuda", mode="sampler_included",
                precision=train_precision, batch=2048)
        hrs = g("train_time_100k_projected", "value", device="cuda", mode="sampler_included",
                precision=train_precision, batch=2048)
        mem = g("train_mem_allocated", "peak", device="cuda", precision=train_precision,
                batch=2048)
        lat_g = g("infer_latency_forward", "median", device="cuda", mode="window_full")
        lat_g95 = g("infer_latency_forward", "p95", device="cuda", mode="window_full")
        lat_c = g("infer_latency_forward", "median", device="cpu", mode="window_full", threads=1)
        lat_c95 = g("infer_latency_forward", "p95", device="cpu", mode="window_full", threads=1)
        im_g = g("infer_mem_allocated", "peak", device="cuda", mode="window")
        im_c = g("infer_mem_rss_increase", "peak", device="cpu", mode="window", threads=1)
        rec = g("infer_latency_forward", "median", device="cuda", mode="recurrent_full_step")
        st = g("recurrent_state_bytes", "value", device="cuda")
        show_rec = m == "cdmamba"
        cells = [fmt(p[0], digits=0), fmt(*size, digits=2), fmt(*sps, digits=4),
                 fmt(*hrs, digits=2), fmt(*mem, digits=0),
                 f"{fmt(lat_g[0], digits=3)} ({fmt(lat_g95[0], digits=3)})",
                 f"{fmt(lat_c[0], digits=3)} ({fmt(lat_c95[0], digits=3)})",
                 fmt(*im_g, digits=1), fmt(*im_c, digits=1),
                 fmt(rec[0], digits=3) if show_rec else "",
                 fmt(st[0] / 1024, digits=1) if show_rec else ""]
        t.rows.append([Cell(DISPLAY[m], "label")] + [Cell(c, "missing" if c == MISSING else "plain")
                                                     for c in cells])
        raw[m] = [p[0], size[0], sps[0], hrs[0], mem[0], lat_g[0], lat_c[0], im_g[0], im_c[0]]
    t.rows.append([Cell("", "rule")])
    for m in OUR_MODELS:
        rel = []
        for i, v in enumerate(raw[m]):
            base = raw["cdt"][i]
            rel.append(MISSING if np.isnan(v) or np.isnan(base) or base == 0 else f"{v / base:.2f}×")
        t.rows.append([Cell(f"{DISPLAY[m]} (rel. to CDT)", "label")] +
                      [Cell(c) for c in rel] + [Cell(""), Cell("")])
    t.col_align = "l" + "c" * len(cols)
    t.notes = ("Measured in a dedicated exclusive job (E6); CPU numbers on the host CPU of a "
               "Snelius A100 node. Recurrent mode is a different inference regime.")
    return t


def table2_baselines(runs: pd.DataFrame) -> Table:
    """Appendix: MLP baselines for reference (params; indicative wall-clock from E2)."""
    t = Table("table2b_baselines_efficiency", "Baselines for reference: parameter count and "
              "indicative training wall-clock of the packed E2 runs (not a controlled "
              "measurement).", [[Cell("Model"), Cell("Params"), Cell("Train h (packed)")]])
    for m in BASELINES:
        d = runs[(runs["exp"] == "E2") & (runs["model"] == m)] if not runs.empty else runs
        if len(d):
            per = d.groupby(["task", "seed"]).first()
            t.rows.append([Cell(DISPLAY[m], "label"), Cell(fmt(per["params_total"].mean(), digits=0)),
                           Cell(fmt(per["train_wall_s"].mean() / 3600, per["train_wall_s"].std() / 3600))])
        else:
            t.rows.append([Cell(DISPLAY[m], "label"), Cell(MISSING), Cell(MISSING)])
    t.col_align = "lcc"
    return t


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--summary", default="summary")
    p.add_argument("--out", default="summary/tables")
    p.add_argument("--train-precision", default="bf16")
    a = p.parse_args()
    s, out = Path(a.summary), Path(a.out)
    runs = load(s / "runs.parquet")
    eff = load(s / "efficiency.parquet")
    if not runs.empty:
        runs["variant"] = runs["variant"].fillna("")
    built = [table1(runs), table2(eff, a.train_precision), table2_baselines(runs),
             table3(runs), table4(runs), table_a1(runs), table_a2(runs), table_a3(runs)]
    for t in built:
        tex = to_latex(_latex_span_fix(_copy(t)))
        out.mkdir(parents=True, exist_ok=True)
        (out / f"{t.name}.tex").write_text(tex)
        (out / f"{t.name}.md").write_text(to_markdown(t))
    print(f"wrote {len(built)} tables to {out}")


def _copy(t: Table) -> Table:
    import copy

    return copy.deepcopy(t)


if __name__ == "__main__":
    main()
